const norm = (s) => String(s || "").replace(/\s+/g, "").toLowerCase();

// 변이 → 정본. 미등록은 공백 1칸 정리한 원형(서로 충돌 안 함).
export function normInstitution(raw) {
  if (!raw) return "";
  const s = norm(raw);
  if (!s) return "";
  for (const [canon, cores] of INSTITUTIONS) {
    for (const c of cores) {
      if (s.includes(norm(c))) return canon;
    }
  }
  return String(raw).replace(/\s+/g, " ").trim();
}

